package com.example.lorestangardesh.ui.tour;

public class PassengerItem {
    public String name;
    public String lastname;
    public String birthdate;
    public String code;

    public PassengerItem(String name, String lastname, String birthdate, String code) {
        this.name = name;
        this.lastname = lastname;
        this.birthdate = birthdate;
        this.code = code;
    }
}
